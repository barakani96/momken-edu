/**
 * EduCore Admin Console - Audit Logs Trail View
 */

import React, { useState, useEffect } from 'react';
import { Tag, Button } from '@carbon/react';
import { Download, Renew } from '@carbon/icons-react';

import { auditLogger, AuditLogEntry } from '../../../../core/auditLogger';
import { AdminPage } from '../../../../ui/admin/AdminPage';
import { AdminDataTable, ColumnDef } from '../../../../ui/admin/AdminDataTable';

import { useTranslation } from 'react-i18next';

export function AuditLogsPage() {
  const [logs, setLogs] = useState<AuditLogEntry[]>([]);
  const { t } = useTranslation();

  const fetchLogs = async () => {
    const records = await auditLogger.getRecentLogs(100);
    setLogs(records);
  };

  useEffect(() => {
    fetchLogs();
  }, []);

  const columns: ColumnDef<AuditLogEntry>[] = [
    { key: 'timestamp', header: t('ui.common.timestamp', 'Timestamp'), render: (row) => new Date(row.timestamp).toLocaleString() },
    { key: 'type', header: t('admin.auditTrail.eventCategory', 'Event Category'), render: (row) => <Tag type="purple" size="sm">{row.type.toUpperCase()}</Tag> },
    { key: 'action', header: t('admin.auditTrail.actionDesc', 'Action Description') },
    { key: 'module', header: t('ui.common.module', 'Module') },
    { key: 'details', header: t('admin.auditTrail.metadataDetails', 'Metadata Details'), render: (row) => <pre style={{ fontSize: '0.75rem', margin: 0 }}>{JSON.stringify(row.details || {})}</pre> },
  ];

  return (
    <AdminPage
      title={t('admin.auditTrail.title', 'Audit Log Trail')}
      description={t('admin.auditTrail.description', 'Immutable institutional audit log recording all administrative actions, data mutations, security access events, and system configuration updates.')}
      breadcrumbs={[{ label: t('shell.nav.adminConsole', 'Admin Console'), href: '/admin' }, { label: t('shell.nav.auditLogs', 'Audit Logs') }]}
      actions={
        <Button renderIcon={Renew} onClick={fetchLogs}>
          {t('admin.auditTrail.refresh', 'Refresh Audit Trail')}
        </Button>
      }
    >
      <AdminDataTable
        title={t('admin.auditTrail.recordsTitle', 'Institutional System Audit Records')}
        description={t('admin.auditTrail.recordsDesc', 'Comprehensive audit trail generated by the core audit logging engine.')}
        columns={columns}
        data={logs}
        searchPlaceholder={t('admin.auditTrail.search', 'Search audit logs by action, module, or user...')}
      />
    </AdminPage>
  );
}
